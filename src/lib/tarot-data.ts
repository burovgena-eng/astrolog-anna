/** FNV-1a хеш строки даты — стабильный, но не механически-последовательный. */
function hashDateKey(dateKey: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < dateKey.length; i++) {
    hash ^= dateKey.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

/** Карта дня: детерминирована по ключу даты «YYYY-MM-DD». */
export function getCardForDate(dateKey: string): TarotCard {
  return majorArcana[hashDateKey(dateKey) % majorArcana.length];
}

/** Ключ сегодняшней даты по Новосибирску (UTC+7) — карта дня меняется в полночь НСК. */
export function todayDateKey(): string {
  const shifted = new Date(Date.now() + NSK_OFFSET_MIN * 60_000);
  const mm = String(shifted.getUTCMonth() + 1).padStart(2, "0");
  const dd = String(shifted.getUTCDate()).padStart(2, "0");
  return `${shifted.getUTCFullYear()}-${mm}-${dd}`;
}

export function getRandomCardShuffle(): TarotCard {
  const index = Math.floor(Math.random() * majorArcana.length);
  return majorArcana[index];
}
